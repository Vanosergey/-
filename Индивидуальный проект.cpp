#include <opencv2/opencv.hpp>// Подключаем главный заголовочный файл OpenCV. Внутри него уже собраны все основные модули: работа с изображениями, видео, камерой, вывод на экран и т.д.
#include <string> // Подключаем стандартную библиотеку для работы со строками (std::string).
using namespace cv;
using namespace std;

int main() {
    string rtsp_url = "rtsp://123456:Artem2017@192.168.2.122:554/stream1"; //Вводим rtsp://Login:Password@IPкамеры:554/stream1(или stream2 для качества 360р)

    VideoCapture cap(rtsp_url); // Создаём объект VideoCapture и сразу пытаемся подключиться к видеопотоку по указанной ссылке. OpenCV сам выберет подходящий бэкенд (в нашем случае — FFmpeg) для декодирования.
    if (!cap.isOpened()) { // Проверяем, удалось ли открыть поток.
        cout << "Не удалось подключиться к камере!" << std::endl;
        return -1; // Если поток не открылся — выходим из программы с кодом -1. Это сигнал операционной системе, что программа завершилась с ошибкой.
    }

    Mat frame; // Создаём пустую матрицу (Mat) для хранения одного кадра. Именно в неё мы будем считывать каждый новый кадр из потока.
    while (true) {    // Бесконечный цикл — пока пользователь не нажмёт ESC.
        cap >> frame; // Считываем очередной кадр из видеопотока в переменную frame. Оператор ">>" перегружен в классе VideoCapture специально для этого.
        if (frame.empty()) break; // Проверяем, не пустой ли кадр. Пустой кадр может означать, что поток прервался, камера отключилась или закончилось видео.
        imshow("Tapo RTSP", frame); // Показываем кадр в окне с заголовком "Tapo RTSP". OpenCV создаёт это окно автоматически при первом вызове.
        if (waitKey(1) == 27) break; // Ждём 1 миллисекунду и проверяем, не нажал ли пользователь клавишу. waitKey возвращает код нажатой клавиши. Клавиша ESC имеет код 27 — если она нажата, выходим из цикла.
    }
    return 0;
}